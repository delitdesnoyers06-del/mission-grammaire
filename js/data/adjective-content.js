// Fonction utilitaire pour obtenir un exercice par ID
export function getAdjectiveExerciseById(id) {
  return adjectiveExercises.find((exercise) => exercise.id === id) || null;
}

// Fonction utilitaire pour obtenir des exercices par niveau
export function getAdjectiveExercisesByDifficulty(difficulty) {
  return adjectiveExercises.filter((exercise) => exercise.difficulty === difficulty);
}

// Fonction utilitaire pour obtenir des exercices par catégorie
export function getAdjectiveExercisesByCategory(category) {
  return adjectiveExercises.filter((exercise) => exercise.category === category);
}

